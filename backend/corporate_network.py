def get_network_summary(symbol: str) -> Dict[str, Any]:
    """
    Computes summary metrics for corporate network and supply chain vulnerability.
    """
    splc = get_supply_chain_network(symbol)
    hold = get_corporate_hierarchy(symbol)

    suppliers = splc.get("suppliers", [])
    customers = splc.get("customers", [])
    contractors = splc.get("independent_contractors", [])
    subsidiaries = hold.get("holding_entities", [])

    sole_source_count = sum(1 for s in suppliers if s.get("is_sole_source"))
    high_dependency_count = sum(1 for s in suppliers if s.get("dependency_pct", 0) >= 10.0)

    clusters = list(set(s.get("cluster", "Other") for s in suppliers))

    return {
        "symbol": splc["symbol"],
        "name": splc["name"],
        "primary_sector": splc["primary_sector"],
        "group_name": hold.get("group_name", "Standalone"),
        "total_suppliers_tracked": len(suppliers),
        "sole_source_bottlenecks": sole_source_count,
        "high_dependency_suppliers": high_dependency_count,
        "total_customer_segments": len(customers),
        "total_independent_contractors": len(contractors),
        "total_holding_subsidiaries": len(subsidiaries),
        "product_clusters": clusters,
        "provenance_summary": {
            "audited_filing_nodes": sum(1 for s in suppliers if s.get("provenance") == "ACTUAL FILING") + sum(1 for sub in subsidiaries if sub.get("provenance") == "ACTUAL FILING"),
            "modelled_estimated_nodes": sum(1 for s in suppliers if s.get("provenance") != "ACTUAL FILING") + sum(1 for sub in subsidiaries if sub.get("provenance") != "ACTUAL FILING"),
        },
    }
